import numpy as np

def client_process(client):
    figsize = client['figureSize']
    if len(figsize) < 2:
        figsize = [1350, 900]
    figw, figh = figsize[0], figsize[1]
    client['figurePosition'] = [figw, figh]

    ages = np.arange(50, 121)
    years = np.arange(2014, 2114)

    def _build_mort_table(m1, m2):
        m3 = np.outer(m2[:, -1], np.ones(86))
        m4 = np.hstack([m1.reshape(-1, 1), 1 - m2, 1 - m3])
        return np.cumprod(m4, axis=1)

    if client['p1Sex'] == 'M':
        m1 = _getRP2014Male()
        m2 = _getMP2014Male()
    else:
        m1 = _getRP2014Female()
        m2 = _getMP2014Female()
    mortTable = _build_mort_table(m1, m2)
    rowNumber = np.where(ages == client['p1Age'])[0][0]
    colNumber = np.where(years == client['Year'])[0][0]
    m5 = mortTable[rowNumber:, colNumber:]
    mortP1 = np.diag(m5)

    if client['p2Sex'] == 'M':
        m1 = _getRP2014Male()
        m2 = _getMP2014Male()
    else:
        m1 = _getRP2014Female()
        m2 = _getMP2014Female()
    mortTable = _build_mort_table(m1, m2)
    rowNumber = np.where(ages == client['p2Age'])[0][0]
    colNumber = np.where(years == client['Year'])[0][0]
    m5 = mortTable[rowNumber:, colNumber:]
    mortP2 = np.diag(m5)

    ncols = max(len(mortP1), len(mortP2))
    mortP1 = np.concatenate([mortP1, np.ones(ncols - len(mortP1))])
    mortP2 = np.concatenate([mortP2, np.ones(ncols - len(mortP2))])
    mortP1 = np.concatenate([[0], mortP1])
    mortP2 = np.concatenate([[0], mortP2])
    ncols += 1
    client['mortP1'] = mortP1
    client['mortP2'] = mortP2

    nrows = client['nScenarios']
    probs = np.outer(np.ones(nrows), mortP1)
    randnums = np.random.rand(nrows, ncols)
    statesP1 = (randnums >= probs).astype(float)
    statesP1 = np.cumprod(statesP1, axis=1)

    probs = np.outer(np.ones(nrows), mortP2)
    randnums = np.random.rand(nrows, ncols)
    statesP2 = (randnums >= probs).astype(float)
    statesP2 = np.cumprod(statesP2, axis=1) * 2

    states = statesP1 + statesP2
    estates = (states[:, 1:] == 0) & (states[:, :-1] > 0)
    estates = np.hstack([np.zeros((nrows, 1)), estates])
    states = states + 4 * estates
    client['pStatesM'] = states

    surv1 = np.cumprod(1 - mortP1)
    propdie1 = surv1[:-1] - surv1[1:]
    client['p1LE'] = round(np.sum(propdie1 * np.arange(1, len(propdie1) + 1)) * 10) / 10

    surv2 = np.cumprod(1 - mortP2)
    propdie2 = surv2[:-1] - surv2[1:]
    client['p2LE'] = round(np.sum(propdie2 * np.arange(1, len(propdie2) + 1)) * 10) / 10

    client['incomesM'] = np.zeros(client['pStatesM'].shape)
    client['feesM'] = np.zeros(client['pStatesM'].shape)
    return client


